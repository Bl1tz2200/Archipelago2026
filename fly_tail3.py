def node(mid):
    """ID метки → (столбец, строка). Это вся карта поля."""
    col, row = mid % GRID, mid // GRID
    return (GRID - 1 - col if FLIP_X else col), row


def mark(col, row):
    """(столбец, строка) → ID метки. Обратная к node."""
    return row * GRID + (GRID - 1 - col if FLIP_X else col)


def nearest(seen, center):
    """Ближайшая к центру кадра метка — та, над которой висим: (ID, замер) или None."""
    if not seen:
        return None
    mid = min(seen, key=lambda i: math.hypot(seen[i][0] - center[0], seen[i][1] - center[1]))
    return mid, seen[mid]


def at(spot):
    """Место на поле для печати: «у метки 23» (ближайший узел, не вылезая за поле)."""
    col = min(max(int(round(spot[0])), 0), GRID - 1)
    row = min(max(int(round(spot[1])), 0), GRID - 1)
    return f"у метки {mark(col, row)}"


def walk(start_id, target_id):
    """Путь от узла к узлу шагами в соседний узел: список ID без начального.

    П. 2.1.3 разрешает только перелёты между соседними узлами, включая
    диагональные (повороты кратно 45°). Поэтому любой перегон через поле —
    вход в цепочку, догон уходящего строя — раскладывается на такие шаги:
    сперва по диагонали, пока расходятся обе координаты, потом прямо.
    """
    col, row = node(start_id)
    tcol, trow = node(target_id)
    path = []
    while (col, row) != (tcol, trow):
        col += (tcol > col) - (tcol < col)
        row += (trow > row) - (trow < row)
        path.append(mark(col, row))
    return path


