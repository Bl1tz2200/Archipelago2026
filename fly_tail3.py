def fly(drone, forward, left, up=0.0):
    """Смещение по корпусу: x вперёд, y влево, z вверх. Команда и пауза — как в примере."""
    distance = math.hypot(forward, left)
    if distance < 0.05 and abs(up) < 0.05:
        return

    # Одна команда длиннее пары шагов сетки — это почти всегда ошибка: не та метка
    # опознана или узел следа пропущен, и цель посчиталась от далёкой опоры.
    # Летим только часть: контур замкнут по меткам, следующий кадр доведёт остаток.
    limit = HOP_MAX_STEPS * STEP_M
    if distance > limit:
        print(f"          перелёт {distance:.1f} м урезан до {limit:.1f} м", flush=True)
        forward, left = forward * limit / distance, left * limit / distance
        distance = limit

    global NAV_FAILS
    # Отказом считается и «success=False», и брошенное исключение: для дрона это
    # одно и то же — команда не выполнена.
    try:
        resp = drone.control.navigate(x=float(forward), y=float(left), z=float(up),
                                      yaw=YAW, speed=SPEED, frame_id="body",
                                      auto_arm=False)
        refused = resp is not None and not getattr(resp, "success", True)
        why = getattr(resp, "message", "")
    except Exception as exc:
        refused, why = True, f"исключение: {exc}"

    # Одиночный отказ бывает и на исправном дроне — просто повторим. А вот отказы
    # подряд означают, что дрон больше не принимает управление (выбило из OFFBOARD,
    # сработал failsafe): слать в пустоту оставшиеся минуты бессмысленно и опасно —
    # прекращаем полёт и садимся.
    if refused:
        NAV_FAILS += 1
        print(f"          navigate отказал ({NAV_FAILS}/{NAV_FAIL_MAX}): {why}", flush=True)
        if NAV_FAILS >= NAV_FAIL_MAX:
            raise FlightAborted(f"navigate отказал {NAV_FAILS} раз подряд")
    else:
        NAV_FAILS = 0
    # navigate возвращается сразу, дрон летит в фоне — ждать окончания приходится
    # паузой. Время в пути считается по длине с вертикалью, а HOP_PAD добавлен на
    # разгон, торможение и успокоение: снимок, сделанный на ещё летящем дроне, даёт
    # промах и раскачку. Дрон дёргается на каждом шаге — увеличивать надо HOP_PAD.
    time.sleep(math.hypot(distance, up) / SPEED + HOP_PAD)


def descending(drone):
    """Следить за посадкой: («пошёл вниз», «сел»).

    Принятая команда `land()` ещё не значит, что дрон садится, — а телеметрии, по
    которой это видно всем остальным, у нас нет. Зато есть та же метка, по которой
    держалась высота: `alt_by_side` даёт оценку, и её падение и есть подтверждение.

    Два ответа, а не один, потому что это два разных факта. Падение высоты на
    LAND_DROP говорит лишь, что снижение началось, — объявлять по нему посадку
    нельзя, дрон в этот момент ещё почти в метре над полом. Касание — это либо
    оценка ниже LAND_DONE, либо пропавшая метка после начавшегося снижения: у
    самого пола камера её уже не охватывает.
    """
    started = False
    limit = time.time() + LAND_S
    while time.time() < limit:
        img = look(drone)
        if img is None:
            time.sleep(0.3)
            continue
        base = nearest(markers(img), (img.shape[1] / 2.0, img.shape[0] / 2.0))
        if base is None:
            if started:
                print("          метки не видно — дрон у самого пола", flush=True)
                return True, True
            time.sleep(0.3)
            continue
        now = alt_by_side(base[1][2])
        if not now:
            return True, True               # эталона нет — проверить нечем, не мешаем
        print(f"          снижение: h≈{now:.1f} м", flush=True)
        if now <= LAND_DONE:
            return True, True
        if now <= ALT * (1.0 - LAND_DROP):
            started = True
        # Без паузы цикл крутится со скоростью камеры: за LAND_S набежали бы сотни
        # строк, смывшие итоговые строки полёта — то, что читают судьи.
        time.sleep(0.3)
    return started, False


def touch_down(drone):
    """Посадить дрон. Команда повторяется, пока дрон не пойдёт вниз.

    Единственный вызов `land()` — слишком слабая гарантия для конца полёта: он может
    вернуть success=False, бросить исключение или быть принятым, но ни к чему не
    привести. Поэтому принятая команда ещё и подтверждается снижением по камере.
    Отдельно подстрахована сигнатура: в документации `land()` описан без аргументов,
    а `timeout` — нет, и на другой сборке библиотеки он даёт TypeError.
    """
    for attempt in range(1, LAND_TRIES + 1):
        try:
            try:
                resp = drone.control.land()
            except TypeError:                       # сборка со старой сигнатурой
                resp = drone.control.land(timeout=10.0)
        except Exception as exc:
            print(f"ПОСАДКА: попытка {attempt} сорвалась — {exc}", flush=True)
            time.sleep(1.0)
            continue

        print(f"ПОСАДКА: попытка {attempt} — {getattr(resp, 'success', '?')} "
              f"{getattr(resp, 'message', '')}", flush=True)
        if resp is not None and not getattr(resp, "success", True):
            time.sleep(1.0)
            continue

        started, landed = descending(drone)
        if landed:
            print("ПОСАДКА: дрон на земле", flush=True)
            return True
        if started:
            # Снижение идёт, но до земли на этом отрезке не дошло — просто ждём его
            # дальше, не пересылая команду: повтор land в середине снижения ничего
            # не улучшает, а лог засоряет.
            print("ПОСАДКА: снижается, ждём касания", flush=True)
            _, landed = descending(drone)
            if landed:
                print("ПОСАДКА: дрон на земле", flush=True)
                return True
        print("ПОСАДКА: снижения не видно — повторяем команду", flush=True)

    print("!" * 54, flush=True)
    print("!!! ПОСАДКА НЕ ПОДТВЕРЖДЕНА — САЖАЙТЕ С ПУЛЬТА НЕМЕДЛЕННО !!!", flush=True)
    print("!" * 54, flush=True)
    # Нода не гаснет, пока есть надежда до дрона достучаться: закрыть её — значит
    # потерять последний канал управления. Команда шлётся дальше, пока пилот не
    # перехватит с пульта или не выйдет LAND_LAST_S.
    last = time.time() + LAND_LAST_S
    while time.time() < last:
        try:
            drone.control.land()
        except Exception as exc:
            print(f"ПОСАДКА: {exc}", flush=True)
        print("!!! САЖАЙТЕ С ПУЛЬТА !!!", flush=True)
        if descending(drone)[1]:
            return True
    return False


def climb(drone):
    """Подняться осмотреться, когда меток не видно, — но не выше предела.

    Пока метки нет, высоту проверить нечем: `hold_alt` работает по её размеру в
    кадре. Значит подъём вслепую надо считать самим и вовремя останавливаться,
    иначе дрон, потерявший поле, будет набирать высоту до самого потолка зоны
    (п. 2.6.3 — не выше 4 м). Как только метка нашлась, счётчик обнуляется:
    дальше высоту держит `hold_alt`.
    """
    global BLIND_UP
    if BLIND_UP + LOOK_UP > CLIMB_MAX:
        print(f"          выше не поднимаемся: набрано {BLIND_UP:.1f} м вслепую",
              flush=True)
        return
    BLIND_UP += LOOK_UP
    print(f"          меток не видно — поднимаемся осмотреться (+{BLIND_UP:.1f} м)",
          flush=True)
    fly(drone, 0.0, 0.0, LOOK_UP)


def grounded(side):
    """Метка в кадре — заменить счисленный подъём на измеренный.

    Обнулять счётчик по одному факту «метка нашлась» нельзя: дрон в этот момент
    ещё наверху, `hold_alt` опускает его лишь по ALT_FIX за команду. Метка снова
    пропала — и был бы доступен новый полный подъём, так высота росла бы
    ступеньками мимо предела. Поэтому пока метку видно, счётчик — это честный
    замер превышения над рабочей высотой, а счисление работает только вслепую.
    """
    global BLIND_UP
    now = alt_by_side(side)
    if now:
        BLIND_UP = max(0.0, now - ALT)


def settle(drone):
    """Дождаться спокойного висения. Возвращает сторону метки на спокойном кадре.

    Признак того, что дрон перестал качать, — метка под ним стоит в кадре: между
    соседними кадрами её центр и размер почти не меняются. Пока этого нет, команд
    не отправляем вовсе: доводка по прыгающей метке раскачивает дрон ещё сильнее.
    """
    previous = None
    calm = 0
    side = 0.0
    for _ in range(SETTLE_TRIES):
        img = look(drone)
        if img is None:
            time.sleep(0.3)
            continue

        base = nearest(markers(img), (img.shape[1] / 2.0, img.shape[0] / 2.0))
        if base is None:
            previous, calm = None, 0
            time.sleep(0.3)
            continue

        mid, (x, y, side, _) = base
        if previous is not None and previous[0] == mid:
            px, py, pside = previous[1]
            drift = math.hypot(x - px, y - py) / side      # сдвиг в долях метки
            zoom = abs(side - pside) / side                # и «дыхание» размера
            if drift < SETTLE_DRIFT and zoom < SETTLE_DRIFT:
                calm += 1
                if calm >= SETTLE_FRAMES:
                    print(f"          висим спокойно (метка {mid}, {side:.0f} px)", flush=True)
                    return side
            else:
                calm = 0
        previous = (mid, (x, y, side))
        time.sleep(0.3)

    print("          успокоиться не вышло — летим как есть", flush=True)
    return side


def hover_at(drone, col, row, deadline=None):
    """Встать в точку поля (столбец, строка), дробную: (встали ли, метка под нами).

    Это `goto` головного дрона, у которого цель — не метка, а место МЕЖДУ метками:
    хвост держится на полшага позади соседа (п. 2.1.4), а над такой точкой метки нет
    по определению. Отсюда два отличия:

      * опорой берётся ближайшая к центру кадра метка, а смещение до цели считается
        по карте от неё — теми же тремя строками, что и перелёт лидера по карте;
      * признак прилёта — длина этого смещения меньше TOL_M МЕТРОВ, а не «метка в
        центре кадра».

    Когда цель совпадает с меткой, смещение по карте обнуляется, и остаётся ровно
    та же доводка по кадру, что у лидера, — отдельная ветка для этого не нужна.

    Вторым значением возвращается метка, от которой считались в последнем кадре:
    это фактическое место дрона, и вызывающему не надо ради него тратить ещё кадр.
    """
    blind = 0
    here = None
    for _ in range(TRIES):
        if deadline is not None and time.time() > deadline:
            return False, here
        img = look(drone)
        if img is None:
            time.sleep(0.5)
            continue

        seen = markers(img)
        height, width = img.shape[:2]
        cx, cy = width / 2.0, height / 2.0
        base = nearest(seen, (cx, cy))
        report(col, row, seen, base[1][2] if base else 0.0)

        if base is None:
            # Не видно вообще ничего: поднимаемся, чтобы расширить обзор. Как только
            # метка найдётся, hold_alt сам вернёт дрон на рабочую высоту.
            blind += 1
            if blind >= BLIND_FRAMES:
                climb(drone)
                blind = 0
            else:
                time.sleep(0.5)
            continue

        blind = 0
        base_id, (x, y, side, angle) = base
        here = base_id
        grounded(side)
        # Пиксели в метры — по стороне самой метки. Камера смотрит вниз: верх кадра
        # это «вперёд», левый край — «влево». Строки поля идут вперёд по корпусу,
        # столбцы — влево; к смещению по сетке добавляем то, насколько сама опорная
        # метка сдвинута от центра кадра.
        scale = MARKER_M / side
        bcol, brow = node(base_id)
        forward, left = to_body((row - brow) * STEP_M, -(col - bcol) * STEP_M, angle)
        forward -= (y - cy) * scale
        left -= (x - cx) * scale

        gap = math.hypot(forward, left)
        if gap <= TOL_M:
            # На месте — заодно вернём высоту, если её увело.
            fly(drone, 0.0, 0.0, hold_alt(side))
            return True, here
        # Перелёт отрабатывается целиком, как шаг лидера по карте: демпфировать его
        # значит лететь один узел двумя-тремя командами и отстать от цепочки. А вот
        # доводку у самой цели придерживаем: без GAIN дрон проскакивает её и начинает
        # качаться от команды к команде. Граница — пара допусков, дальше это уже не
        # доводка, а перелёт.
        damp = GAIN if gap < 3.0 * TOL_M else 1.0
        fly(drone, forward * damp, left * damp, hold_alt(side))

    print(f"          {at((col, row))}: не довели за {TRIES} попыток", flush=True)
    return False, here


def hop(drone, here, target, deadline=None):
    """Шаг в сторону `target` — только в СОСЕДНИЙ узел. Возвращает, где оказались.

    П. 2.1.3 и модель движения разрешают перелёты лишь между соседними узлами сетки,
    включая диагональные (повороты кратно 45°). Правило действует и на подходе к
    строю, поэтому длинный путь раскладывается на такие шаги, а не пролетается
    напрямик. За виток делается один шаг: к следующему лидер мог уйти дальше, и цель
    всё равно пересчитывается заново.
    """
    if here == target:
        return here
    step = walk(here, target)[0]
    reached, seen_id = hover_at(drone, *node(step), deadline=deadline)
    if reached:
        return step
    # Не довели: где дрон на самом деле, знает камера, а не план.
    return seen_id if seen_id is not None else here


def follow(drone, plan, here):
    """Идти за лидером «след в след», пока не подойдёт время посадки.

    Место дрона — точка следа в LAG_STEPS шага позади головы. Пока он до неё не
    дошёл, идёт догон, и только соседними узлами (см. `hop`). Цель догона — всегда
    узел СЛЕДА, поэтому вход в цепочку происходит там, где требует п. 2.1.2: в узел,
    который цепочка уже прошла и который хвост только что освободил, — а не сбоку,
    не спереди и не в середину строя.

    Дальше `here` ведётся как звено следа, а не как то, что видно в кадре: стоя ровно
    между двумя метками, дрон опознавал бы под собой то одну, то другую и дёргался бы
    между ними. С камерой место сверяется только когда шаг не удался.

    Догон вообще возможен потому, что лидер на яблоке стоит и ждёт доклада
    (п. 2.1.2): JOIN_WAIT_S минус время на взлёт и скан — это десяток перелётов,
    как раз путь от стартового угла до середины поля.
    """
    land_at = T0 + LAND_AT_S
    joined_said = False
    while time.time() < land_at:
        listen()
        trail, head = slot(plan)
        j, f = back_along(trail, head, LAG_STEPS * STEP_M)
        goal = trail[j]

        # Сбой на одном витке не должен ронять весь полёт: доложили и пробуем снова.
        # Ctrl+C, KILL SWITCH и FlightAborted этим не перехватываются — они уводят
        # программу сразу на посадку.
        try:
            if here != goal:
                here = hop(drone, here, goal, land_at)
                if here != goal:
                    continue        # ещё догоняем, цель пересчитается на следующем витке
                # Дошли до своего звена — и доводку на дробную точку делаем ТУТ ЖЕ,
                # не откладывая до следующего витка. Иначе дрон замирает ровно на
                # узле, то есть на целый шаг позади соседа: 1 м вместо 0.5, и всё
                # время движения цепочки дистанция вдвое больше предела п. 2.1.4.

            if not joined_said:
                print(f">>> ДРОН {TAIL_NUM} В ЦЕПОЧКЕ: звено {j} следа, метка {goal}",
                      flush=True)
                joined_said = True
            # На своём звене: доводимся на дробную точку внутри отрезка следа и
            # докладываем лидеру, что встали.
            if hover_at(drone, *spot(trail, j, f), deadline=land_at)[0]:
                report_ready()
                # Стоим на месте: без паузы виток крутится со скоростью камеры, и за
                # минуту ожидания набегают сотни строк, смывающие всё остальное.
                # Лидер проходит узел за несколько секунд — треть секунды тут ничего
                # не решает.
                time.sleep(0.3)
        except FlightAborted:
            raise
        except Exception as exc:
            print(f"          сбой на витке: {exc}", flush=True)
            time.sleep(0.5)

    print(f"время вышло ({LAND_AT_S:.0f} с от старта) — садимся", flush=True)


def scan(drone):
    """Стартовая метка со взлёта и три эталона на весь полёт.

    Скан лидера без чтения фигуры и яблок: хвост их не ищет (п. 2.1.2 — яблоки
    считает только камера лидера). Замер делается по спокойному кадру: на раскачке
    он увёл бы эталоны на весь оставшийся полёт.

      * SIDE_REF  — сторона метки на рабочей высоте («как выглядит поле с ALT»);
      * ANGLE_REF — поворот меток в кадре, то есть курс, от которого дальше
        считается отклонение;
      * STEP_M    — шаг сетки площадки, измеренный по двум соседним меткам.
    """
    global SIDE_REF, ANGLE_REF, STEP_M
    calm_side = settle(drone)
    blind = 0
    for _ in range(TRIES):
        img = look(drone)
        if img is None:
            time.sleep(0.5)
            continue
        seen = markers(img)
        if not seen:
            # Как и в полёте: не видно ничего — поднимаемся расширить обзор. Без
            # стартовой метки в цепочку не встать, так что пробуем всерьёз.
            blind += 1
            if blind >= BLIND_FRAMES:
                climb(drone)
                blind = 0
            else:
                print("меток не видно, ищем…", flush=True)
                time.sleep(0.5)
            continue
        under_sight = nearest(seen, (img.shape[1] / 2.0, img.shape[0] / 2.0))
        under = under_sight[0]
        SIDE_REF = calm_side or under_sight[1][2]
        ANGLE_REF = under_sight[1][3]
        # Масштаб для замера шага — сторона метки В ЭТОМ кадре, не эталон из другого:
        # между спокойным кадром и этим дрон мог всплыть, и шаг вышел бы кривым.
        measured = grid_step(seen, under_sight[1][2])
        print("=" * 54, flush=True)
        print(f">>> ХВОСТОВОЙ ДРОН {TAIL_NUM}: держимся {LAG_STEPS:.2f} шага "
              f"позади лидера по следу", flush=True)
        print(f">>> МЕТКА ПОД ДРОНОМ: {under}  (узел {node(under)})", flush=True)
        print(f">>> ВЫСОТА {ALT} м = метка {SIDE_REF:.0f} px в кадре (эталон)", flush=True)
        # Замер принимается, только если он близок к настроенному шагу. Настройка
        # меряется рулеткой, а замер зависит от MARKER_M и от того, верно ли опознаны
        # метки, — и кривой замер портит сразу всё: длину перелётов по карте, предел
        # урезания команды (HOP_MAX_STEPS * STEP_M) и дистанцию в строю.
        if not measured:
            print(f">>> ШАГ СЕТКИ: соседей в кадре нет, оставляем {STEP_M:.2f} м", flush=True)
        elif abs(measured - STEP_M) <= STEP_TOL * STEP_M:
            print(f">>> ШАГ СЕТКИ: {measured:.2f} м (замер по соседним меткам, "
                  f"в настройках было {STEP_M:.2f})", flush=True)
            STEP_M = measured
        else:
            # Замер и настройка расходятся ровно во столько раз, во сколько ошиблись
            # в стороне метки: масштаб кадра считается как MARKER_M / сторона.
            print(f"!!! ШАГ СЕТКИ: замер {measured:.2f} м не сходится с настройкой "
                  f"{STEP_M:.2f} м — оставляем настройку", flush=True)
            print(f"!!! ПРОВЕРЬТЕ MARKER_M ({MARKER_M} м): похоже, сторона метки "
                  f"задана в {measured / STEP_M:.2f} раза неверно", flush=True)
        print(f">>> ДИСТАНЦИЯ ДО ЛИДЕРА: {LAG_STEPS * STEP_M:.2f} м по следу "
              f"(до соседа {GAP_STEPS * STEP_M:.2f} м, предел п. 2.1.4 — 0.50 м)",
              flush=True)
        print(f">>> ВИДНО МЕТОК: {' '.join(str(i) for i in sorted(seen))}", flush=True)
        print(f">>> СЛЕД ЛИДЕРА: "
              f"{' '.join(str(i) for i in TRAIL) or 'маячка не слышно, летим по расчёту'}",
              flush=True)
        print("=" * 54, flush=True)
        return under
    print("стартовая метка не опознана", flush=True)
    return None


def main():
    drone = sverk_interfaces.init(Nodename=f"fly_tail{TAIL_NUM}")
    patch_yuv(drone)
    airborne = False    # дрон мог оторваться от земли — значит обязан и сесть
    try:
        # П. 2.1.2: дрон отрывается от земли не по расписанию, а когда лидер
        # распознал очередное яблоко. Ждём своё.
        if not wait_apple():
            return      # взлёта не было — и сажать нечего

        print(f"ВЗЛЁТ на {ALT} м", flush=True)
        # Флаг ставится ДО команды: отказ взлёта ещё не значит, что дрон остался на
        # земле, и посадку в таком случае надо всё равно выполнить.
        airborne = True
        # Набор высоты на своей, пониженной скорости: чем мягче взлёт, тем меньше
        # раскачка наверху. Пауза — время самого набора плюс запас на успокоение.
        resp = drone.control.navigate(x=0.0, y=0.0, z=ALT, yaw=YAW, speed=CLIMB_SPEED,
                                      frame_id="body", auto_arm=True)
        print(f"взлёт: {getattr(resp, 'success', '?')} {getattr(resp, 'message', '')}",
              flush=True)
        if resp is not None and not getattr(resp, "success", True):
            # Не встал в OFFBOARD или не заармился — вставать в строй нечем.
            raise RuntimeError("взлёт не принят — дрон остаётся на земле")
        time.sleep(ALT / CLIMB_SPEED + SETTLE_S)

        here = scan(drone)
        if here is None:
            print("без стартовой метки в цепочку не встать", flush=True)
        else:
            # Расчётный маршрут лидера — только на случай, если маячок молчит.
            plan = search_route(here if LEAD_START is None else LEAD_START)
            follow(drone, plan, here)
    finally:
        # Взлетели — обязаны сесть, чем бы ни кончился полёт. Садимся на месте:
        # к этому моменту дроны разнесены по следу на GAP_STEPS шага и никому не
        # мешают. Общий таймер делает посадку роя синхронной (п. 2.1.5).
        # Дрону, который так и не взлетал, команда land не нужна вовсе.
        try:
            if airborne:
                print("ПОСАДКА", flush=True)
                touch_down(drone)
        finally:
            drone.close()


if __name__ == "__main__":
    main()
