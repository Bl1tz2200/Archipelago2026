def add_node(mid):
    """Дописать узел в след — или отмотать след, если лидер вернулся назад.

    Дубли не пишутся: лидер шлёт маячок и на каждом узле, и каждые полсекунды, пока
    ждёт присоединения.

    Возврат в один из последних TRAIL_BACK узлов — это разворот, а не новый кусок
    пути. Дописать его значило бы растянуть след «туда и обратно» по одному отрезку,
    и тогда дроны 1 и 3 получили бы ОДНУ И ТУ ЖЕ точку: полшага назад от головы по
    возвратной ветке и полтора назад по прямой — это середина одного и того же
    отрезка. Поэтому след отматывается до найденного узла, и цепочка выстраивается
    позади него по прежнему пути — так, как она физически и стоит.

    Окно короткое нарочно: замкнутый контур фигуры (10–18 узлов) возвращается в
    точку входа законно, и схлопывать его в один узел нельзя.
    """
    if TRAIL and TRAIL[-1] == mid:
        return                      # лидер всё ещё на том же узле
    back = TRAIL[-TRAIL_BACK:]
    if mid in back:
        del TRAIL[len(TRAIL) - len(back) + back.index(mid) + 1:]
        return
    TRAIL.append(mid)


def listen():
    """Забрать всё, что накопилось от маячка лидера. Не блокирует.

    Узлы копятся в TRAIL: это и есть след, по которому хвост пойдёт «след в след»
    (п. 2.1.4), — не предсказанный маршрут, а те узлы, которые лидер действительно
    прошёл, в том же порядке.

    Слушать надо ещё на земле: к моменту взлёта у хвоста уже есть весь след от
    стартового угла, и куда входить в цепочку — вычисляется, а не угадывается.

    Чужое отсеивается тремя полями. Ключ команды — программы других команд на том же
    порту. Номер запуска — зависший экземпляр нашей же программы: держимся за
    наибольший услышанный, так свежий пуск лидера побеждает старый. Взлетев, номер
    больше не меняем: перезапуск лидера посреди полёта не должен обнулять след под
    дроном, который уже стоит в строю. Счётчик — переставленные и повторные
    датаграммы: устаревший «H» иначе отмотал бы след назад по ложному «развороту».

    Сокет неблокирующий, датаграммы копятся в буфере ядра между вызовами: отдельный
    поток не нужен, а значит нечему и отвалиться в фоне посреди полёта.
    """
    global LEAD_APPLES, LEAD_HEARD, LEAD_RUN, LEAD_SEQ, LAND_NOW
    while True:
        try:
            data, _ = _BEACON.recvfrom(128)
        except OSError:             # буфер пуст (BlockingIOError) или сокет не открылся
            return
        parts = data.split()
        # "<ключ> H <узел> <яблок> <запуск> <счётчик>" или "<ключ> L <запуск> <счётчик>"
        if len(parts) < 4 or parts[0] != TEAM.encode():
            continue                # чужая команда или обрезанная датаграмма
        verb = parts[1]
        if verb == b"H" and len(parts) == 6:
            body, run, seq = parts[2:4], parts[4], parts[5]
        elif verb == b"L" and len(parts) == 4:
            body, run, seq = [], parts[2], parts[3]
        else:
            continue                # чей-то доклад «T» или мусор на порту
        try:
            run, seq = int(run), int(seq)
            body = [int(v) for v in body]
        except ValueError:
            continue

        if run < LEAD_RUN or (AIRBORNE and run != LEAD_RUN):
            continue                # прошлый запуск лидера, или мы уже в строю
        if run > LEAD_RUN:
            # Лидер перезапустился: прежний след — от другого полёта, он не наш.
            LEAD_RUN, LEAD_SEQ = run, 0
            TRAIL.clear()
            LEAD_APPLES = 0
        if seq <= LEAD_SEQ:
            continue                # переставленная или повторная датаграмма
        LEAD_SEQ = seq
        LEAD_HEARD = time.time()

        if verb == b"L":
            if not LAND_NOW:
                print(">>> ЛИДЕР СКОМАНДОВАЛ ПОСАДКУ", flush=True)
            LAND_NOW = True
            continue
        mid, count = body
        if not 0 <= mid < GRID * GRID:
            continue                # такого узла на поле нет — мусор
        add_node(mid)
        LEAD_APPLES = max(LEAD_APPLES, count)


def report_ready():
    """Доложить лидеру, что дрон встал в хвост (п. 2.1.2).

    Шлётся на каждом витке, пока дрон стоит на своём месте: ни счётчиков, ни
    состояния. Лидер складывает номера в множество, повтор ему не мешает, зато
    потерянная датаграмма исправляется сама на следующем витке. Без этого доклада
    лидер провисит на яблоке весь JOIN_WAIT_S и проест время сборки (п. 2.1.3).

    Номер запуска в докладе — лидера, а не свой: лидер принимает только доклады со
    своим номером, иначе зависший с прошлого раза хвост «встал бы в хвост» за него.
    """
    global SEQ
    SEQ += 1
    msg = f"{TEAM} T {TAIL_NUM} {LEAD_RUN} {SEQ}".encode()
    # Широковещательно и, если PEERS заполнен, лидеру лично: при разных подсетях
    # или изоляции клиентов доходит только второе. Дубль лидеру не мешает — номера
    # доложившихся он складывает в множество.
    for addr in [BEACON_ADDR] + PEERS:
        try:
            _BEACON.sendto(msg, (addr, BEACON_PORT))
        except OSError as exc:
            print(f"          доклад не ушёл на {addr}: {exc}", flush=True)


def slot():
    """Где сейчас голова цепочки: индекс последнего узла следа.

    Маячок замолчал посреди полёта — след замирает на последнем услышанном узле, и
    хвост просто держит место, пока не подойдёт посадка. Это безопаснее любых
    догадок: лидера всё равно не видно, а лететь «куда-то вперёд» вслепую значит
    его догнать. Счисления по часам здесь нет намеренно — см. шапку файла.
    """
    return len(TRAIL) - 1


def back_along(trail, head, gap_m):
    """Место в gap_m метрах позади узла trail[head]: (звено, доля, «след короче»).

    Точка лежит на отрезке следа между trail[j] и trail[j+1], в доле f от trail[j].
    Так место всегда привязано к ОТРЕЗКУ СЛЕДА, и хвост, подтягиваясь, идёт вдоль
    него, а не режет угол напрямик (модель движения, пп. 3-4).

    Отставание отматывается по ДЛИНЕ следа, а не по числу узлов: диагональный перелёт
    длиннее прямого в 1.41 раза, и «полшага» по нему вышло бы 0.71 м — уже за
    пределом 50 см (п. 2.1.4).

    Третьим значением — признак того, что след КОРОЧЕ нужного отставания: лидер ещё
    не отошёл от начала следа на дистанцию строя, и места для этого дрона позади него
    физически нет. Место при этом возвращается начальное, но лететь туда нельзя — в
    вырожденном случае (след из одного узла) это ровно тот узел, над которым лидер
    сейчас и висит. Что с этим делать, решает `follow`.
    """
    left = gap_m / STEP_M               # остаток пути назад, в шагах сетки
    j = head
    while left > 1e-6 and j > 0:
        col, row = node(trail[j])
        pcol, prow = node(trail[j - 1])
        seg = math.hypot(pcol - col, prow - row)    # длина отрезка в шагах: 1 или 1.41
        if seg <= 1e-6:
            j -= 1
            continue
        if seg >= left:
            return j - 1, 1.0 - left / seg, False
        left -= seg
        j -= 1
    return j, 0.0, left > 1e-6


def spot(trail, j, f):
    """Точка следа (звено j, доля f) в узлах поля: (столбец, строка), дробные.

    Звено подрезается по длине следа: между тем, как его посчитали, и тем, как сюда
    дошли, успевает отработать `listen` — а разворот лидера след укорачивает.
    """
    j = min(j, len(trail) - 1)
    col, row = node(trail[j])
    if f <= 1e-6 or j + 1 >= len(trail):
        return float(col), float(row)
    ncol, nrow = node(trail[j + 1])
    return col + (ncol - col) * f, row + (nrow - row) * f


def wait_apple():
    """Ждать на земле своё яблоко (п. 2.1.2). True — взлетаем, False — остаёмся.

    Одно яблоко — один дрон: пока лидер не сообщил, что распознал TAIL_NUM-е яблоко,
    отрываться от земли нельзя. Лишний дрон в воздухе — это не спасение попытки, а
    нарушение строя, за которое эксперты снимают баллы.

    Пока ждём, маячок пишется в след — к моменту отрыва хвост знает весь путь лидера
    от стартового угла и попадает в цепочку сразу, а не ищет её.

    Взлёта «по часам» здесь нет: без маячка дрон остаётся на земле, сколько бы ни
    прошло времени. Причина в шапке файла — вслепую строй не удержать, а три хвоста
    на несинхронных таймерах идут по одному маршруту навстречу друг другу.

    Рой сел или своё яблоко так и не нашлось — остаёмся на земле: взлетать под конец
    попытки незачем, а сесть обратно дрон может и не успеть.
    """
    print(f"ДРОН {TAIL_NUM} НА ЗЕМЛЕ: ждём яблоко {TAIL_NUM} по маячку "
          f"(без маячка не взлетаем)", flush=True)
    said = -1
    while True:
        listen()
        if LAND_NOW:
            print(f">>> рой садится, а яблоко {TAIL_NUM} не найдено — "
                  f"остаёмся на земле", flush=True)
            return False
        if LEAD_APPLES >= TAIL_NUM:
            print(f">>> ЛИДЕР РАСПОЗНАЛ ЯБЛОКО {LEAD_APPLES} — ВЗЛЕТАЕМ", flush=True)
            return True
        waited = time.time() - T0
        if waited >= LAND_AT_S:
            print(f">>> яблоко {TAIL_NUM} за {waited:.0f} с так и не найдено — "
                  f"остаёмся на земле", flush=True)
            return False
        if int(waited) // 5 != said:        # строка в лог раз в пять секунд, не чаще
            said = int(waited) // 5
            print(f"          ждём {waited:.0f} с: лидер "
                  f"{f'на узле {TRAIL[-1]}' if TRAIL else 'молчит'}, "
                  f"яблок {LEAD_APPLES}", flush=True)
        time.sleep(0.2)


