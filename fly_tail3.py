#  ВЫСОТА — по метке
# ═══════════════════════════════════════════════════════════════════════
#
# `navigate(frame_id="body", z=0)` держит не высоту, а «сколько было в момент
# команды»: цель считается от текущего положения. При разгоне дрон наклоняется и
# слегка всплывает, следующая команда принимает эту высоту за норму — и ошибка
# копится только вверх, тем быстрее, чем чаще команды.
#
# Лечится тем же, чем и всё остальное здесь, — меткой: её сторона в пикселях
# обратно пропорциональна высоте. Запоминаем сторону на рабочей высоте сразу после
# взлёта и дальше каждой командой возвращаемся к ней. Телеметрия не нужна.
#
# Для цепочки это ещё и требование строя: п. 2.1.4 и модель движения запрещают
# «лесенку» — все дроны идут в одной горизонтальной плоскости. Высота у всех
# считается по одной и той же формуле от одинаковых меток, так что плоскость
# получается общей без всякой связи между дронами.

SIDE_REF = 0.0      # сторона метки на рабочей высоте, пиксели (замер после взлёта)
ANGLE_REF = None    # поворот меток в кадре на взлёте — «нос смотрит туда же, что и тогда»
BLIND_UP = 0.0      # превышение над рабочей высотой, м: замер по метке или счисление
NAV_FAILS = 0       # отказов navigate подряд
TURN_WARNED = False # про повёрнутую метку ругаемся один раз, а не на каждом кадре


class FlightAborted(RuntimeError):
    """Дальше лететь нечем: команды управления не принимаются. Только на посадку."""


def alt_by_side(side):
    """Оценка высоты по стороне метки в кадре, м. 0.0 — эталон ещё не замерен."""
    if SIDE_REF <= 1.0 or side <= 1.0:
        return 0.0
    return ALT * SIDE_REF / side


def hold_alt(side):
    """На сколько подняться (+) или опуститься (−), чтобы вернуться на рабочую высоту."""
    now = alt_by_side(side)
    if not now:
        return 0.0
    correction = ALT - now
    if abs(correction) < 0.05:          # мёртвая зона: не дёргаем дрон по мелочи
        return 0.0
    return max(-ALT_FIX, min(ALT_FIX, correction))


# ═══════════════════════════════════════════════════════════════════════
#  КУРС — тоже по метке
# ═══════════════════════════════════════════════════════════════════════
#
# Смещения, посчитанные ПО КАДРУ (метка левее/выше центра), в поправке не
# нуждаются: кадр поворачивается вместе с дроном. А вот смещения ПО КАРТЕ
# («место на два узла вперёд») заданы в осях поля — если дрон отвернуло, их надо
# развернуть в оси корпуса. Насколько отвернуло, показывает поворот метки в
# кадре: на поле они уложены одинаково.


def turn_error(angle):
    """На сколько дрон отвернулся от курса взлёта, радианы (−π…π).

    Курс читается по повороту метки в кадре, а это верно лишь пока все метки на поле
    уложены одинаково. Метка, положенная повёрнутой, дала бы «увод» в десятки градусов
    и развернула бы на столько же все перелёты по карте, считанные от неё, — дрон
    полетел бы поперёк. Каждая команда navigate удерживает курс, так что увод больше
    TURN_MAX неправдоподобен: это раскладка поля, а не полёт, и поправка отбрасывается.
    """
    global TURN_WARNED
    if ANGLE_REF is None:
        return 0.0
    error = (angle - ANGLE_REF + math.pi) % (2 * math.pi) - math.pi
    if abs(error) > math.radians(TURN_MAX):
        if not TURN_WARNED:
            print(f"!!! поворот метки {math.degrees(error):+.0f}° — дрон так не отворачивает. "
                  f"Похоже, метка на поле лежит повёрнутой; поправку курса игнорируем",
                  flush=True)
            TURN_WARNED = True
        return 0.0
    return error


def to_body(forward, left, angle):
    """Вектор из осей поля в оси корпуса с учётом того, что дрон отвернуло."""
    error = turn_error(angle)
    if abs(error) < math.radians(YAW_DEAD):     # мелочь, не крутим
        return forward, left
    c, s = math.cos(error), math.sin(error)
    return forward * c + left * s, -forward * s + left * c


def hold_yaw(angle):
    """Доворот к курсу взлёта для очередной команды navigate, радианы.

    Ровно то же, что hold_alt делает с высотой, только для курса: замер снимается с
    метки, а поправка отдаётся ближайшей же команде перелёта — отдельной команды
    разворота не нужно, у navigate для этого есть свой аргумент.

    Знак. `turn_error` даёт увод ПРОТИВ часовой, и положительный yaw в body — это тоже
    против часовой (в документации `set_yaw(-pi/2)` описан как поворот по часовой).
    Значит отработать увод — это скомандовать ему обратный знак.

    Отдаём не весь увод разом, а не больше YAW_FIX: дрон крутится и летит по одной и
    той же команде, и на большом довороте кадр смазывается сильнее, чем стоит того
    выигрыш. Мелочь внутри YAW_DEAD не трогаем вовсе — иначе дрон дёргался бы на шуме
    опознания метки. Увод неправдоподобно большой (повёрнутая метка на поле) уже
    отсеян в `turn_error`, и здесь придёт нулём.
    """
    error = turn_error(angle)
    if abs(error) < math.radians(YAW_DEAD):
        return 0.0
    limit = math.radians(YAW_FIX)
    return max(-limit, min(limit, -error))


def grid_step(seen, side):
    """Шаг сетки в метрах, измеренный по двум соседним меткам в кадре.

    Избавляет от ручной подгонки STEP_M: расстояние между соседями в пикселях,
    переведённое масштабом метки, и есть шаг площадки. Нет пары соседей — 0.0.
    """
    for a in seen:
        for b in seen:
            if a >= b:
                continue
            (acol, arow), (bcol, brow) = node(a), node(b)
            if abs(acol - bcol) + abs(arow - brow) != 1:
                continue                    # не соседи по сетке
            gap = math.hypot(seen[a][0] - seen[b][0], seen[a][1] - seen[b][1])
            return gap * MARKER_M / side
    return 0.0


