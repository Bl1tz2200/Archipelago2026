    try:
        img = drone.image.take_picture(timeout=2.0)
    except Exception as exc:
        print(f"кадр не получен: {exc}", flush=True)
        return None
    if img is None or getattr(img, "ndim", 0) != 3 or img.size == 0:
        return None
    return img


