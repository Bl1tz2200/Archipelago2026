class FlightAborted(RuntimeError):
    """Дальше лететь нечем: команды управления не принимаются. Только на посадку."""


def alt_by_side(side):
    """Оценка высоты по стороне метки в кадре, м. 0.0 — эталон ещё не замерен."""
    if SIDE_REF <= 1.0 or side <= 1.0:
        return 0.0
    return ALT * SIDE_REF / side


def hold_alt(side):
    """На сколько подняться (+) или опуститься (−), чтобы вернуться на рабочую высоту."""
    now = alt_by_side(side)
    if not now:
        return 0.0
    correction = ALT - now
    if abs(correction) < 0.05:          # мёртвая зона: не дёргаем дрон по мелочи
        return 0.0
    return max(-ALT_FIX, min(ALT_FIX, correction))


# ═══════════════════════════════════════════════════════════════════════
#  КУРС — тоже по метке
# ═══════════════════════════════════════════════════════════════════════
#
# Смещения, посчитанные ПО КАДРУ (метка левее/выше центра), в поправке не
# нуждаются: кадр поворачивается вместе с дроном. А вот смещения ПО КАРТЕ
# («цель на два узла вперёд») заданы в осях поля — если дрон отвернуло, их надо
# развернуть в оси корпуса. Насколько отвернуло, показывает поворот метки в
# кадре: на поле они уложены одинаково.


def turn_error(angle):
    """На сколько дрон отвернулся от курса взлёта, радианы (−π…π).

    Курс читается по повороту метки в кадре, а это верно лишь пока все метки на поле
    уложены одинаково. Метка, положенная повёрнутой, дала бы «увод» в десятки градусов
    и развернула бы на столько же все перелёты по карте, считанные от неё, — дрон
    полетел бы поперёк. Каждая команда navigate удерживает курс, так что увод больше
    TURN_MAX неправдоподобен: это раскладка поля, а не полёт, и поправка отбрасывается.
    """
    global TURN_WARNED
    if ANGLE_REF is None:
        return 0.0
    error = (angle - ANGLE_REF + math.pi) % (2 * math.pi) - math.pi
    if abs(error) > math.radians(TURN_MAX):
        if not TURN_WARNED:
            print(f"!!! поворот метки {math.degrees(error):+.0f}° — дрон так не отворачивает. "
                  f"Похоже, метка на поле лежит повёрнутой; поправку курса игнорируем",
                  flush=True)
            TURN_WARNED = True
        return 0.0
    return error


def to_body(forward, left, angle):
    """Вектор из осей поля в оси корпуса с учётом того, что дрон отвернуло."""
    error = turn_error(angle)
    if abs(error) < math.radians(YAW_DEAD):     # мелочь, не крутим
        return forward, left
    c, s = math.cos(error), math.sin(error)
    return forward * c + left * s, -forward * s + left * c


def hold_yaw(angle):
    """Доворот к курсу взлёта для очередной команды navigate, радианы.

    Ровно то же, что hold_alt делает с высотой, только для курса: замер снимается с
    метки, а поправка отдаётся ближайшей же команде перелёта — отдельной команды
    разворота не нужно, у navigate для этого есть свой аргумент.

    Знак. `turn_error` даёт увод ПРОТИВ часовой (проверено дважды: по развороту метки
    в осях кадра и по матрице в to_body), а положительный yaw в body — это тоже против
    часовой (в документации `set_yaw(-pi/2)` описан как поворот по часовой). Значит
    отработать увод — это скомандовать ему обратный знак.

    Отдаём не весь увод разом, а не больше YAW_FIX: дрон крутится и летит по одной и
    той же команде, и на большом довороте кадр смазывается сильнее, чем стоит того
    выигрыш. Мелочь внутри YAW_DEAD не трогаем вовсе — иначе дрон дёргался бы на шуме
    опознания метки. Увод неправдоподобно большой (повёрнутая метка на поле) уже
    отсеян в `turn_error`, и здесь придёт нулём.
    """
    error = turn_error(angle)
    if abs(error) < math.radians(YAW_DEAD):
        return 0.0
    limit = math.radians(YAW_FIX)
    return max(-limit, min(limit, -error))


def grid_step(seen, side):
    """Шаг сетки в метрах, измеренный по двум соседним меткам в кадре.

    Избавляет от ручной подгонки STEP_M: расстояние между соседями в пикселях,
    переведённое масштабом метки, и есть шаг площадки. Нет пары соседей — 0.0.
    """
    for a in seen:
        for b in seen:
            if a >= b:
                continue
            (acol, arow), (bcol, brow) = node(a), node(b)
            if abs(acol - bcol) + abs(arow - brow) != 1:
                continue                    # не соседи по сетке
            gap = math.hypot(seen[a][0] - seen[b][0], seen[a][1] - seen[b][1])
            return gap * MARKER_M / side
    return 0.0


def place(base, x, y):
    """Где точка кадра лежит на поле: (столбец, строка) в узлах сетки, дробные.

    Отсчёт от видимой метки: сторона метки задаёт масштаб, её ID — узел. Столбцы
    растут вправо по кадру, строки — вверх, ровно как в перелётах (см. `goto`).

    Кадр повёрнут вместе с дроном, а узлы сетки — нет, поэтому смещение по кадру
    разворачивается в оси поля (обратное преобразование к `to_body`). Без этого
    отвёрнутому дрону одно и то же яблоко кажется лежащим в разных узлах — и
    засчитывается дважды.
    """
    base_id, (bx, by, side, angle) = base
    scale = MARKER_M / side / STEP_M          # пиксель → доля шага сетки
    forward, left = -(y - by) * scale, -(x - bx) * scale
    error = turn_error(angle)
    if abs(error) >= math.radians(3):
        c, s = math.cos(error), math.sin(error)
        forward, left = forward * c - left * s, forward * s + left * c
    col, row = node(base_id)
    return col - left, row + forward


def at(spot):
    """Место на поле для печати: «у метки 23» (ближайший узел, не вылезая за поле)."""
    col = min(max(int(round(spot[0])), 0), GRID - 1)
    row = min(max(int(round(spot[1])), 0), GRID - 1)
    return f"у метки {mark(col, row)}"


# Запись о яблоке — изменяемый список, чтобы неподтверждённое можно было дотянуть
# до подтверждения на следующем проходе: [цвет, столбец, строка, долетели, попыток].
COLOUR, COL, ROW, REACHED, ATTEMPTS = range(5)


def sure(found):
    """Сколько яблок подтверждено долётом — только они останавливают поиск."""
    return sum(1 for apple in found if apple[REACHED])


def counted(found, spot):
    """Уже известное яблоко на этом месте или None. Опознаём ТОЛЬКО по месту.

    Не по цвету — по двум причинам сразу. Несколько яблок на зачёте могут быть
    одного цвета, поэтому «такой цвет уже был» ничего не значит. И наоборот: границы
    оттенков стоят впритык (красное до H=9, жёлтое с H=10), так что пограничное
    яблоко на соседних кадрах может опознаться то так, то этак — а если цвет входит
    в опознание, одно и то же яблоко засчитается дважды и займёт чужой слот.

    Место же не скачет: оно меряется от метки под дроном и уточняется при подлёте.

    Возвращается сама запись, а не «да/нет»: неподтверждённое яблоко надо уметь
    дотянуть до подтверждения на следующем проходе, а не запирать навсегда.
    """
    for apple in found:
        if math.hypot(apple[COL] - spot[0], apple[ROW] - spot[1]) < MERGE_STEPS:
            return apple
    return None


def walk(start_id, target_id):
    """Путь от узла к узлу шагами в соседний узел: список ID без начального.

    П. 2.1.3 разрешает лидеру только перелёты между соседними узлами, включая
    диагональные (повороты кратно 45°). Поэтому любой перегон через поле —
    возврат на старт, выход из неугловой стартовой точки — раскладывается на
    такие шаги: сперва по диагонали, пока расходятся обе координаты, потом прямо.
    """
    col, row = node(start_id)
    tcol, trow = node(target_id)
    path = []
    while (col, row) != (tcol, trow):
        col += (tcol > col) - (tcol < col)
        row += (trow > row) - (trow < row)
        path.append(mark(col, row))
    return path


def search_route(start_id):
    """Маршрут поиска яблок: змейка по полю от стартового угла.

    Соседние узлы маршрута — соседние узлы сетки (п. 2.1.3). Строки берутся через
    SEARCH_ROW_STEP, а промежуточные проходятся по одному узлу на развороте, чтобы
    не было прыжка через клетку.

    Змейка всегда начинается из угла — так она накрывает поле целиком. Если дрон
    почему-то стартовал не с угловой метки, путь до ближайшего угла добавляется
    спереди теми же соседними шагами.
    """
    col0, row0 = node(start_id)
    ccol = 0 if col0 * 2 < GRID - 1 else GRID - 1
    crow = 0 if row0 * 2 < GRID - 1 else GRID - 1
    cols = list(range(GRID)) if ccol == 0 else list(range(GRID - 1, -1, -1))
    step = SEARCH_ROW_STEP if crow == 0 else -SEARCH_ROW_STEP
    rows = list(range(crow, GRID if crow == 0 else -1, step))

    route = []
    for i, row in enumerate(rows):
        line = cols if i % 2 == 0 else cols[::-1]
        route += [mark(col, row) for col in line]
        if i + 1 < len(rows):
            # разворот: спускаемся на следующую полосу по одному узлу
            down = 1 if rows[i + 1] > row else -1
            route += [mark(line[-1], r) for r in range(row + down, rows[i + 1], down)]
    # Маршрут всегда начинается с узла, на котором дрон уже стоит. Путь до угла
    # заканчивается самим углом, поэтому от змейки берётся хвост без её первого узла.
    return [start_id] + walk(start_id, route[0]) + route[1:]


def figure_route(corner_id):
    """Контур назначенной фигуры: (название, список узлов). None — фигуры нет.

    Первый узел списка — уже СЛЕДУЮЩИЙ за стартовым: дрон на стартовой метке стоит,
    и вести его туда, где он есть, незачем. Последний узел — сама стартовая метка:
    контур замкнут, как требует Приложение 3 («возвращается в точку входа»).

    Вершины в FIGURES заданы внутрь поля от угла, поэтому одна запись работает из
    любого угла: направление «внутрь» определяется тем, у какой границы угол стоит.
    Рёбра раскладываются той же `walk`, что и всё остальное, — значит вся фигура
    летится соседними шагами с поворотами кратно 45° (п. 2.1.3).
    """
    if corner_id not in FIGURES:
        return None
    name, verts = FIGURES[corner_id]
    col0, row0 = node(corner_id)
    dcol = 1 if col0 == 0 else -1       # «внутрь поля» от той границы, где стоит угол
    drow = 1 if row0 == 0 else -1
    nodes = [mark(col0 + a * dcol, row0 + b * drow) for a, b in verts]

    route = []
    for i, here in enumerate(nodes):
        route += walk(here, nodes[(i + 1) % len(nodes)])
    return name, route


