def fly(drone, forward, left, up=0.0, turn=0.0):
    """Смещение по корпусу: x вперёд, y влево, z вверх, turn — доворот курса.

    Команда и пауза — как в примере из документации; `turn` уходит в тот же navigate
    штатным аргументом `yaw`, отдельной команды разворота не появляется.
    """
    distance = math.hypot(forward, left)
    # Доворот проверяется наравне со смещением: дрон, уже стоящий над целью, никуда
    # не летит — и без этой проверки накопленный увод курса не отрабатывался бы
    # ровно там, где его важнее всего убрать, на зависании.
    if distance < 0.05 and abs(up) < 0.05 and abs(turn) < math.radians(YAW_DEAD):
        return

    # Одна команда длиннее пары шагов сетки — это почти всегда ошибка: не та метка
    # опознана или узел маршрута пропущен, и цель посчиталась от далёкой опоры.
    # Летим только часть: контур замкнут по меткам, следующий кадр доведёт остаток.
    limit = HOP_MAX_STEPS * STEP_M
    if distance > limit:
        print(f"          перелёт {distance:.1f} м урезан до {limit:.1f} м", flush=True)
        forward, left = forward * limit / distance, left * limit / distance
        distance = limit

    global NAV_FAILS
    # Отказом считается и «success=False», и брошенное исключение: для дрона это
    # одно и то же — команда не выполнена. Раньше исключение летело мимо счётчика
    # и гасло в обработчике узла, так что полёт продолжался с неуправляемым дроном.
    try:
        resp = drone.control.navigate(x=float(forward), y=float(left), z=float(up),
                                      yaw=float(turn), speed=SPEED, frame_id="body",
                                      auto_arm=False)
        refused = resp is not None and not getattr(resp, "success", True)
        why = getattr(resp, "message", "")
    except Exception as exc:
        refused, why = True, f"исключение: {exc}"

    # Одиночный отказ бывает и на исправном дроне — просто повторим. А вот отказы
    # подряд означают, что дрон больше не принимает управление (выбило из OFFBOARD,
    # сработал failsafe): слать в пустоту оставшиеся минуты бессмысленно и опасно —
    # прекращаем полёт и садимся.
    if refused:
        NAV_FAILS += 1
        print(f"          navigate отказал ({NAV_FAILS}/{NAV_FAIL_MAX}): {why}", flush=True)
        if NAV_FAILS >= NAV_FAIL_MAX:
            raise FlightAborted(f"navigate отказал {NAV_FAILS} раз подряд")
    else:
        NAV_FAILS = 0
    # navigate возвращается сразу, дрон летит в фоне — ждать окончания приходится
    # паузой. Время в пути считается по длине с вертикалью, а HOP_PAD добавлен на
    # разгон, торможение и успокоение: снимок, сделанный на ещё летящем дроне, даёт
    # промах и раскачку. Дрон дёргается на каждом шаге — увеличивать надо HOP_PAD.
    time.sleep(math.hypot(distance, up) / SPEED + HOP_PAD)


def descending(drone):
    """Следить за посадкой: («пошёл вниз», «сел»).

    Принятая команда `land()` ещё не значит, что дрон садится, — а телеметрии, по
    которой это видно всем остальным, у нас нет. Зато есть та же метка, по которой
    держалась высота: `alt_by_side` даёт оценку, и её падение и есть подтверждение.

    Два ответа, а не один, потому что это два разных факта. Падение высоты на
    LAND_DROP говорит лишь, что снижение началось, — объявлять по нему посадку
    нельзя, дрон в этот момент ещё почти в метре над полом. Касание — это либо
    оценка ниже LAND_DONE, либо пропавшая метка после начавшегося снижения: у
    самого пола камера её уже не охватывает.
    """
    started = False
    limit = time.time() + LAND_S
    while time.time() < limit:
        img = look(drone)
        if img is None:
            time.sleep(0.3)
            continue
        base = nearest(markers(img), (img.shape[1] / 2.0, img.shape[0] / 2.0))
        if base is None:
            if started:
                print("          метки не видно — дрон у самого пола", flush=True)
                return True, True
            time.sleep(0.3)
            continue
        now = alt_by_side(base[1][2])
        if not now:
            return True, True               # эталона нет — проверить нечем, не мешаем
        print(f"          снижение: h≈{now:.1f} м", flush=True)
        if now <= LAND_DONE:
            return True, True
        if now <= ALT * (1.0 - LAND_DROP):
            started = True
        # Без паузы цикл крутится со скоростью камеры: за LAND_S набежали бы сотни
        # строк, смывшие итоговую сводку по яблокам и фигуре — то, что читают судьи.
        time.sleep(0.3)
    return started, False


def touch_down(drone):
    """Посадить дрон. Команда повторяется, пока дрон не пойдёт вниз.

    Единственный вызов `land()` — слишком слабая гарантия для конца полёта: он может
    вернуть success=False, бросить исключение или быть принятым, но ни к чему не
    привести. Поэтому принятая команда ещё и подтверждается снижением по камере.
    Отдельно подстрахована сигнатура: в документации `land()` описан без аргументов,
    а `timeout` — нет, и на другой сборке библиотеки он даёт TypeError.
    """
    for attempt in range(1, LAND_TRIES + 1):
        try:
            try:
                resp = drone.control.land()
            except TypeError:                       # сборка со старой сигнатурой
                resp = drone.control.land(timeout=10.0)
        except Exception as exc:
            print(f"ПОСАДКА: попытка {attempt} сорвалась — {exc}", flush=True)
            time.sleep(1.0)
            continue

        print(f"ПОСАДКА: попытка {attempt} — {getattr(resp, 'success', '?')} "
              f"{getattr(resp, 'message', '')}", flush=True)
        if resp is not None and not getattr(resp, "success", True):
            time.sleep(1.0)
            continue

        started, landed = descending(drone)
        if landed:
            print("ПОСАДКА: дрон на земле", flush=True)
            return True
        if started:
            # Снижение идёт, но до земли на этом отрезке не дошло — просто ждём его
            # дальше, не пересылая команду: повтор land в середине снижения ничего
            # не улучшает, а лог засоряет.
            print("ПОСАДКА: снижается, ждём касания", flush=True)
            _, landed = descending(drone)
            if landed:
                print("ПОСАДКА: дрон на земле", flush=True)
                return True
        print("ПОСАДКА: снижения не видно — повторяем команду", flush=True)

    print("!" * 54, flush=True)
    print("!!! ПОСАДКА НЕ ПОДТВЕРЖДЕНА — САЖАЙТЕ С ПУЛЬТА НЕМЕДЛЕННО !!!", flush=True)
    print("!" * 54, flush=True)
    # Нода не гаснет, пока есть надежда до дрона достучаться: закрыть её — значит
    # потерять последний канал управления. Команда шлётся дальше, пока пилот не
    # перехватит с пульта или не выйдет LAND_LAST_S.
    last = time.time() + LAND_LAST_S
    while time.time() < last:
        try:
            drone.control.land()
        except Exception as exc:
            print(f"ПОСАДКА: {exc}", flush=True)
        print("!!! САЖАЙТЕ С ПУЛЬТА !!!", flush=True)
        if descending(drone)[1]:
            return True
    return False


def climb(drone):
    """Подняться осмотреться, когда меток не видно, — но не выше предела.

    Пока метки нет, высоту проверить нечем: `hold_alt` работает по её размеру в
    кадре. Значит подъём вслепую надо считать самим и вовремя останавливаться,
    иначе дрон, потерявший поле, будет набирать высоту до самого потолка зоны
    (п. 2.6.3 — не выше 4 м). Как только метка нашлась, счётчик обнуляется:
    дальше высоту держит `hold_alt`.
    """
    global BLIND_UP
    if BLIND_UP + LOOK_UP > CLIMB_MAX:
        print(f"          выше не поднимаемся: набрано {BLIND_UP:.1f} м вслепую",
              flush=True)
        return
    BLIND_UP += LOOK_UP
    print(f"          меток не видно — поднимаемся осмотреться (+{BLIND_UP:.1f} м)",
          flush=True)
    # Курс тут не доворачиваем: читать его тоже не с чего, метки в кадре нет.
    fly(drone, 0.0, 0.0, LOOK_UP)


def grounded(side):
    """Метка в кадре — заменить счисленный подъём на измеренный.

    Обнулять счётчик по одному факту «метка нашлась» нельзя: дрон в этот момент
    ещё наверху, `hold_alt` опускает его лишь по ALT_FIX за команду. Метка снова
    пропала — и был бы доступен новый полный подъём, так высота росла бы
    ступеньками мимо предела. Поэтому пока метку видно, счётчик — это честный
    замер превышения над рабочей высотой, а счисление работает только вслепую.
    """
    global BLIND_UP
    now = alt_by_side(side)
    if now:
        BLIND_UP = max(0.0, now - ALT)


def settle(drone):
    """Дождаться спокойного висения. Возвращает сторону метки на спокойном кадре.

    Признак того, что дрон перестал качать, — метка под ним стоит в кадре: между
    соседними кадрами её центр и размер почти не меняются. Пока этого нет, команд
    не отправляем вовсе: доводка по прыгающей метке раскачивает дрон ещё сильнее.
    """
    previous = None
    calm = 0
    side = 0.0
    for _ in range(SETTLE_TRIES):
        img = look(drone)
        if img is None:
            time.sleep(0.3)
            continue

        base = nearest(markers(img), (img.shape[1] / 2.0, img.shape[0] / 2.0))
        if base is None:
            previous, calm = None, 0
            time.sleep(0.3)
            continue

        mid, (x, y, side, _) = base
        if previous is not None and previous[0] == mid:
            px, py, pside = previous[1]
            drift = math.hypot(x - px, y - py) / side      # сдвиг в долях метки
            zoom = abs(side - pside) / side                # и «дыхание» размера
            if drift < SETTLE_DRIFT and zoom < SETTLE_DRIFT:
                calm += 1
                if calm >= SETTLE_FRAMES:
                    print(f"          висим спокойно (метка {mid}, {side:.0f} px)", flush=True)
                    return side
            else:
                calm = 0
        previous = (mid, (x, y, side))
        time.sleep(0.3)

    print("          успокоиться не вышло — летим как есть", flush=True)
    return side


def approach(drone, colour, deadline=None):
    """Подвестись над яблоком нужного цвета: (место на поле, долетели ли).

    Место — (столбец, строка) в узлах сетки или None, если яблока с самого начала
    не разглядеть. Второе значение честно говорит, встал ли дрон над яблоком: оно
    False и когда яблоко потерялось из кадра, и когда попытки кончились на подлёте.
    Раньше обоими случаями возвращалась просто последняя оценка места, и вызывающий
    считал их успехом.

    `deadline` тот же, что у `goto`: подлёт — это до восьми перелётов, и без него
    яблоко, найденное на последних секундах, вытащило бы поиск за отведённые три
    минуты.
    """
    where = None
    for _ in range(TRIES):
        if deadline is not None and time.time() > deadline:
            return where, False
        img = look(drone)
        if img is None:
            time.sleep(0.5)
            continue

        spot = next((s for s in apples(img) if s[0] == colour), None)
        if spot is None:
            return where, False

        height, width = img.shape[:2]
        cx, cy = width / 2.0, height / 2.0
        _, x, y = spot

        # Масштаб кадра — по стороне видимой метки; без метки метров не посчитать.
        base = nearest(markers(img), (cx, cy))
        if base is None:
            return where, False
        grounded(base[1][2])
        where = place(base, x, y)

        if math.hypot(x - cx, y - cy) <= TOL * math.hypot(width, height):
            # Над яблоком — вернуть высоту и курс.
            fly(drone, 0.0, 0.0, hold_alt(base[1][2]), hold_yaw(base[1][3]))
            return where, True
        # GAIN < 1: не отрабатываем весь промах разом, иначе дрон проскакивает цель.
        scale = MARKER_M / base[1][2] * GAIN
        fly(drone, -(y - cy) * scale, -(x - cx) * scale,
            hold_alt(base[1][2]), hold_yaw(base[1][3]))
    return where, False


def watch(drone, base, fruit, found, deadline=None):
    """Новое яблоко в кадре → подлететь, зависнуть, засчитать. True — засчитали.

    Метки и яблоки кадра приходят уже разобранными: на кадре 1280×950 второй разбор
    того же кадра стоил бы заметной паузы в наведении.

    Каждое яблоко засчитывается однократно (п. 2.1.2) и опознаётся по месту на поле —
    см. `counted`. Яблоко, к которому подлететь не удалось, при следующей встрече
    пробуется снова (до APPLE_RETRIES раз): иначе оно оставалось бы неподтверждённым
    навсегда, а подтверждённых так и не набралось бы три.
    """
    if base is None:
        return False        # без метки места не посчитать — разберёмся на следующем кадре

    for colour, x, y in fruit:
        known = counted(found, place(base, x, y))
        if known is not None and (known[REACHED] or known[ATTEMPTS] >= APPLE_RETRIES):
            continue        # подтверждено или уже пробовали столько, сколько стоит

        # Место с края кадра прикидочное, поэтому подлетаем и уточняем его над яблоком.
        where, reached = approach(drone, colour, deadline)
        if where is None:
            # Яблоко пропало сразу на подлёте — это тоже попытка. Иначе известное
            # неподтверждённое пятно пробовалось бы на каждом кадре и никогда не
            # упёрлось бы в APPLE_RETRIES.
            if known is not None:
                known[ATTEMPTS] += 1
            continue
        known = known or counted(found, where)

        # Номер — по счёту РАСПОЗНАННЫХ, а не подтверждённых долётом: баллы регламент
        # даёт за распознавание (п. 2.1.2), и эту строку читают судьи. По
        # подтверждённым нумеровать нельзя — первое же яблоко, над которым не удалось
        # встать точно, печаталось бы как «ЯБЛОКО 0/3».
        if known is None:
            # Яблоко засчитывается и когда встать точно над ним не вышло, но остановку
            # поиска приближают только подтверждённые: иначе одно ложное пятно, к
            # которому не удалось подлететь, оборвало бы поиск на двух настоящих.
            found.append([colour, where[0], where[1], reached, 1])
            number = len(found)
            note = "" if reached else " (встать над ним не вышло, в зачёт по распознаванию)"
            tail = f" (здесь взлетает дрон {number + 1})"
        else:
            known[ATTEMPTS] += 1
            if not reached:
                continue                        # не вышло и в этот раз — идём дальше
            known[COL], known[ROW], known[REACHED] = where[0], where[1], True
            number = next(i for i, apple in enumerate(found, 1) if apple is known)
            note = " (подтверждено со второго захода)"
            tail = ""      # дрон под это яблоко взлетел ещё когда его распознали

        print(f">>> ЯБЛОКО {number}/{APPLES_TOTAL}: {colour} {at(where)}{note}"
              f" — зависаем {HOVER_S} с{tail}", flush=True)
        time.sleep(HOVER_S)
        return True
    return False


def goto(drone, target, found, deadline=None, tol=None, tries=None, hunt=True):
    """Долететь до метки `target`, попутно высматривая яблоки. True — встали над ней.

    `deadline` — момент, после которого узел бросается недоведённым: три минуты на
    поиск считаются по регламенту, а не по числу оставшихся попыток.

    `tol` и `tries` задают, насколько упорно доводить дрон до узла. На пролётных
    узлах поисковой змейки точность не нужна — там важен обзор, а яблоки ищутся на
    каждом кадре, — поэтому туда идут грубые SEARCH_TOL/SEARCH_TRIES, и весь облёт
    поля укладывается в отведённые три минуты. Точное наведение остаётся там, где
    от него что-то зависит: подлёт к яблоку и возврат на старт.

    `hunt=False` выключает погоню за яблоками: на возврате поиск уже закончен
    (п. 2.1.3), и отвлекаться на них — значит есть время из общего лимита попытки.
    """
    tol = TOL if tol is None else tol
    tries = TRIES if tries is None else tries
    blind = 0
    for _ in range(tries):
        if deadline is not None and time.time() > deadline:
            return False
        img = look(drone)
        if img is None:
            time.sleep(0.5)
            continue

        seen = markers(img)
        fruit = apples(img) if hunt else []
        height, width = img.shape[:2]
        cx, cy = width / 2.0, height / 2.0
        base = nearest(seen, (cx, cy))
        report(target, seen, fruit, base[1][2] if base else 0.0)
        if hunt and watch(drone, base, fruit, found, deadline):
            # Дрон сошёл с узла ради яблока — следующий заход доведёт его до цели.
            continue

        if target in seen:
            x, y, side, angle = seen[target]
            grounded(side)
            if math.hypot(x - cx, y - cy) <= tol * math.hypot(width, height):
                print(f"          над меткой {target}", flush=True)
                # Встали над меткой — заодно вернём высоту и курс, если их увело.
                fly(drone, 0.0, 0.0, hold_alt(side), hold_yaw(angle))
                return True
            # Пиксели в метры — по стороне самой метки. Камера смотрит вниз:
            # верх кадра — это «вперёд», левый край — «влево».
            # GAIN < 1: отрабатываем не весь промах разом, иначе дрон проскакивает
            # цель и начинает качаться от команды к команде.
            scale = MARKER_M / side * GAIN
            fly(drone, -(y - cy) * scale, -(x - cx) * scale,
                hold_alt(side), hold_yaw(angle))
            continue

        # Цели в кадре нет — идём к ней по карте от той метки, что видно.
        if base is None:
            # Не видно вообще ничего: поднимаемся, чтобы расширить обзор. Как только
            # метка найдётся, hold_alt сам вернёт дрон на рабочую высоту.
            blind += 1
            if blind >= BLIND_FRAMES:
                climb(drone)
                blind = 0
            else:
                time.sleep(0.5)
            continue

        blind = 0
        base_id, (x, y, side, angle) = base
        grounded(side)
        scale = MARKER_M / side
        dcol = node(target)[0] - node(base_id)[0]
        drow = node(target)[1] - node(base_id)[1]
        # Строки поля идут вперёд по корпусу, столбцы — влево; к смещению по сетке
        # добавляем то, насколько сама опорная метка сдвинута от центра кадра.
        forward, left = to_body(drow * STEP_M, -dcol * STEP_M, angle)
        fly(drone,
            forward - (y - cy) * scale,
            left - (x - cx) * scale,
            hold_alt(side),
            hold_yaw(angle))

    print(f"          узел {target} пропущен", flush=True)
    return False


def underneath(drone):
    """Метка прямо под дроном — фактическое место, а не то, где он должен был быть.

    Нужна перед возвратом: маршрут мог оборваться на пропущенном узле, а подлёты к
    яблокам уводят дрон с сетки. Строить возврат от последнего узла маршрута значило
    бы считать путь от точки, где дрона нет.
    """
    for _ in range(TRIES):
        img = look(drone)
        if img is None:
            time.sleep(0.5)
            continue
        base = nearest(markers(img), (img.shape[1] / 2.0, img.shape[0] / 2.0))
        if base is not None:
            return base[0]
        time.sleep(0.5)
    return None


def scan(drone):
    """Стартовый угол со взлёта: (метка под дроном, угловая метка) или (None, None).

    Две метки, а не одна: маршрут поиска строится от той, над которой дрон реально
    висит, а фигуру назначает УГЛОВАЯ (Приложение 3), и это может быть не одно и то
    же — дрон могло сдуть на соседний узел ещё на наборе высоты.

    Здесь же замеряется эталон высоты: сторона метки в кадре сразу после взлёта —
    это «как выглядит поле с рабочей высоты ALT». Замер делается по спокойному
    кадру. Заодно снимаются ещё два эталона: ANGLE_REF — поворот меток в кадре,
    то есть курс, от которого дальше считается отклонение, и STEP_M — шаг сетки
    площадки, измеренный по двум соседним меткам.
    """
    global SIDE_REF, ANGLE_REF, STEP_M
    calm_side = settle(drone)
    blind = 0
    for _ in range(TRIES):
        img = look(drone)
        if img is None:
            time.sleep(0.5)
            continue
        seen = markers(img)
        if not seen:
            # Как и в полёте: не видно ничего — поднимаемся расширить обзор. Без
            # стартовой метки не будет ни фигуры, ни маршрута, так что пробуем всерьёз.
            blind += 1
            if blind >= BLIND_FRAMES:
                climb(drone)
                blind = 0
            else:
                print("меток не видно, ищем…", flush=True)
                time.sleep(0.5)
            continue
        under_sight = nearest(seen, (img.shape[1] / 2.0, img.shape[0] / 2.0))
        under = under_sight[0]
        SIDE_REF = calm_side or under_sight[1][2]
        ANGLE_REF = under_sight[1][3]
        # Масштаб для замера шага — сторона метки В ЭТОМ кадре, не эталон из другого:
        # между спокойным кадром и этим дрон мог всплыть, и шаг вышел бы кривым.
        measured = grid_step(seen, under_sight[1][2])
        fruit = ", ".join(name for name, _, _ in apples(img))
        print("=" * 54, flush=True)
        print(f">>> СТАРТОВЫЙ МАРКЕР: {under}  (узел {node(under)})", flush=True)
        print(f">>> ВЫСОТА {ALT} м = метка {SIDE_REF:.0f} px в кадре (эталон)", flush=True)
        # Замер принимается, только если он близок к настроенному шагу. Настройка
        # меряется рулеткой, а замер зависит от MARKER_M и от того, верно ли опознаны
        # метки, — и кривой замер портит сразу всё: длину перелётов по карте, предел
        # урезания команды (HOP_MAX_STEPS * STEP_M) и пересчёт места яблок. Занизится
        # вдвое — дрон будет ползти по полшага и никуда не долетит.
        if not measured:
            print(f">>> ШАГ СЕТКИ: соседей в кадре нет, оставляем {STEP_M:.2f} м", flush=True)
        elif abs(measured - STEP_M) <= STEP_TOL * STEP_M:
            print(f">>> ШАГ СЕТКИ: {measured:.2f} м (замер по соседним меткам, "
                  f"в настройках было {STEP_M:.2f})", flush=True)
            STEP_M = measured
        else:
            # Замер и настройка расходятся ровно во столько раз, во сколько ошиблись
            # в стороне метки: масштаб кадра считается как MARKER_M / сторона.
            print(f"!!! ШАГ СЕТКИ: замер {measured:.2f} м не сходится с настройкой "
                  f"{STEP_M:.2f} м — оставляем настройку", flush=True)
            print(f"!!! ПРОВЕРЬТЕ MARKER_M ({MARKER_M} м): похоже, сторона метки "
                  f"задана в {measured / STEP_M:.2f} раза неверно", flush=True)
        # Фигуру назначает УГЛОВАЯ метка (Приложение 3). Обычно она и есть метка под
        # дроном, но если дрон сдуло на соседний узел — берём ближайшую угловую из
        # кадра: иначе потеряли бы баллы за декодирование на пустом месте.
        corner = nearest({i: v for i, v in seen.items() if i in FIGURES},
                         (img.shape[1] / 2.0, img.shape[0] / 2.0))
        if corner is None:
            print(">>> ФИГУРА НЕ ОПРЕДЕЛЕНА: угловой метки в кадре нет", flush=True)
        else:
            print(f">>> МАРКЕР УГЛА: {corner[0]} → ФИГУРА: {FIGURES[corner[0]][0]}",
                  flush=True)
        print(f">>> ВИДНО МЕТОК: {' '.join(str(i) for i in sorted(seen))}", flush=True)
        print(f">>> ЯБЛОКИ: {fruit or 'не видно'}", flush=True)
        print("=" * 54, flush=True)
        return under, (corner[0] if corner else None)
    print("стартовый угол не опознан", flush=True)
    return None, None


def main():
    drone = sverk_interfaces.init(Nodename="fly_head")
    patch_yuv(drone)
    try:
        print(f"ВЗЛЁТ на {ALT} м", flush=True)
        # Три минуты на сборку формации идут с момента взлёта, а не с набора высоты.
        deadline = time.time() + SEARCH_LIMIT_S
        # Набор высоты на своей, пониженной скорости: чем мягче взлёт, тем меньше
        # раскачка наверху. Пауза — время самого набора плюс запас на успокоение.
        resp = drone.control.navigate(x=0.0, y=0.0, z=ALT, yaw=YAW, speed=CLIMB_SPEED,
                                      frame_id="body", auto_arm=True)
        print(f"взлёт: {getattr(resp, 'success', '?')} {getattr(resp, 'message', '')}",
              flush=True)
        if resp is not None and not getattr(resp, "success", True):
            # Не встал в OFFBOARD или не заармился: дальше лететь нечем, и три минуты
            # «поиска яблок» дрон просто простоял бы на земле.
            raise RuntimeError("взлёт не принят — миссия отменена")
        time.sleep(ALT / CLIMB_SPEED + SETTLE_S)

        start, corner = scan(drone)
        found = []
        if start is None:
            print("без стартовой метки поиск невозможен", flush=True)
        else:
            route = search_route(start)
            print(f"ПОИСК ЯБЛОК: {len(route)} узлов, {SEARCH_LIMIT_S:.0f} с "
                  f"или {APPLES_TOTAL} шт.", flush=True)
            for target in route:
                if sure(found) >= APPLES_TOTAL:
                    print("все яблоки найдены", flush=True)
                    break
                if time.time() > deadline:
                    print("время на поиск вышло", flush=True)
                    break
                # Сбой на одном узле не должен ронять всю попытку: доложили и летим
                # дальше. Ctrl+C, KILL SWITCH и FlightAborted этим не перехватываются —
                # они уводят программу сразу на посадку.
                try:
                    goto(drone, target, found, deadline,
                         tol=SEARCH_TOL, tries=SEARCH_TRIES)
                except FlightAborted:
                    raise
                except Exception as exc:
                    print(f"          узел {target}: сбой — {exc}", flush=True)

            listing = ", ".join(f"{a[COLOUR]} {at((a[COL], a[ROW]))}"
                                f"{'' if a[REACHED] else '?'}" for a in found)
            print("=" * 54, flush=True)
            print(f">>> НАЙДЕНО ЯБЛОК: {sure(found)}/{APPLES_TOTAL} подтверждено"
                  f"{f', всего распознано {len(found)}' if len(found) > sure(found) else ''}"
                  f" ({listing or 'ни одного'})", flush=True)
            print("=" * 54, flush=True)
            # П. 2.1.3: «лидер приводит цепочку на стартовую позицию и с неё начинает
            # выполнение назначенной фигуры». Точка входа — УГЛОВАЯ метка: она же
            # назначила фигуру, и в неё же контур замкнётся. Не опозналась — идём на
            # метку под дроном при взлёте, хоть сядем на стартовой зоне (п. 2.1.5).
            # Проверка именно на None, а не «or»: метка 0 — это настоящий угол поля
            # (Приложение 3, «Квадрат»), и как ложь она подменялась бы стартовой. Дрон,
            # которого сдуло с угла 0 на соседний узел, терял на этом всю фигуру.
            entry = start if corner is None else corner
            # Заход — по соседним узлам (п. 2.1.3), а не одним броском через поле: и
            # регламент соблюдён, и дрон всю дорогу видит метки под собой. Откуда
            # идти — спрашиваем у камеры: после пропущенных узлов и подлётов к
            # яблокам дрон стоит не там, где кончился маршрут.
            under = underneath(drone)
            here = start if under is None else under
            print(f"ЗАХОД на точку входа {entry} (сейчас под нами {here})", flush=True)
            # Путь перестраивается после каждой неудачи: недоведённый узел означает,
            # что дрон не там, где считает план, и остаток пути от прежнего плана
            # уже не годится. Фактическое место опять спрашиваем у камеры.
            back_by = time.time() + RETURN_LIMIT_S
            stuck = 0
            for _ in range(GRID * 2):
                if here == entry:
                    print(f"          на точке входа {entry}", flush=True)
                    break
                if stuck >= BACK_STUCK or time.time() > back_by:
                    # Заход не двигается: начинать фигуру не с той метки — значит
                    # рисовать её не там, где её ждут судьи. Садимся где стоим.
                    print("          заход не идёт — фигуру не начинаем", flush=True)
                    break
                path = walk(here, entry)
                try:
                    # hunt=False: поиск закончен, отвлекаться на яблоки больше нельзя —
                    # это время из общего лимита попытки, а не из трёх минут сборки.
                    if goto(drone, path[0], found, back_by, hunt=False):
                        here, stuck = path[0], 0
                        continue
                except FlightAborted:
                    raise
                except Exception as exc:
                    print(f"          узел {path[0]}: сбой — {exc}", flush=True)
                stuck += 1
                under = underneath(drone)
                here = here if under is None else under
                print(f"          перестраиваем заход от метки {here}", flush=True)

            # ── ФИГУРА (п. 2.1.3, Приложение 3) ──────────────────────────────
            # Фигура ЛЕТАЕТСЯ, а не выстраивается из дронов: цепочка проходит узлы
            # контура в заданном порядке и возвращается в точку входа, сохраняя
            # строй «след в след». Точность здесь штатная (TOL/TRIES), а не грубая
            # SEARCH_*: в поиске важен был обзор, здесь — форма траектории, и её же
            # судят по числу и длине сегментов, углам поворотов и замыканию контура.
            plan = figure_route(entry)
            if here != entry:
                print(f"ФИГУРА НЕ ВЫПОЛНЯЕТСЯ: не дошли до точки входа {entry}",
                      flush=True)
            elif plan is None:
                print(f"ФИГУРА НЕ ВЫПОЛНЯЕТСЯ: метка {entry} не угловая и фигуры "
                      f"не назначает (Приложение 3)", flush=True)
            else:
                name, contour = plan
                figure_by = time.time() + FIGURE_LIMIT_S
                print("=" * 54, flush=True)
                print(f">>> ФИГУРА «{name}»: {len(contour)} узлов от метки {entry}, "
                      f"{FIGURE_LIMIT_S:.0f} с", flush=True)
                print("=" * 54, flush=True)
                stuck = 0
                for target in contour:
                    if time.time() > figure_by:
                        print("время на фигуру вышло — контур не замкнут", flush=True)
                        break
                    if stuck >= FIGURE_STUCK:
                        print("фигура не идёт — прекращаем контур", flush=True)
                        break
                    try:
                        if goto(drone, target, found, figure_by, hunt=False):
                            here, stuck = target, 0
                            continue
                    except FlightAborted:
                        raise
                    except Exception as exc:
                        print(f"          узел {target}: сбой — {exc}", flush=True)
                    stuck += 1
                else:
                    print("=" * 54, flush=True)
                    print(f">>> ФИГУРА «{name}» ПРОЙДЕНА, контур замкнут на метке "
                          f"{entry}", flush=True)
                    print("=" * 54, flush=True)
            # Возврата после фигуры нет: контур замкнут на стартовой метке, дрон и
            # так стоит в стартовой зоне — по п. 2.1.5 остаётся только сесть.
    finally:
        # Взлетели — обязаны сесть, чем бы ни кончился полёт.
        try:
            print("ПОСАДКА", flush=True)
            touch_down(drone)
        finally:
            drone.close()


if __name__ == "__main__":
    main()
